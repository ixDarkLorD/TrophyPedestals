"""Builds the site's reference and changelog pages from the mod's own docs, so the site never drifts from them.

    python tools/sync_docs.py [path to the Trophy Pedestals 26.1.2 folder]

It reads docs/reference.md and CHANGELOG.md from the mod (by default the sibling folder ../TrophyPedestals-26.1.2),
splits the reference into one page per topic, and rewrites its links so they point at the right page. Edit the mod's
docs, then rerun this; don't edit the generated pages, which it overwrites (each says so at its top). The overview,
guide, downloads and license pages are the site's own and are left alone.
"""
import json
import os
import re
import sys

SITE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
DOCS = os.path.join(SITE, 'docs')
MOD = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(SITE, '..', 'TrophyPedestals-26.1.2'))
NOTICE = '<!-- Generated by tools/sync_docs.py from the mod\'s {source}: edit that, then rerun the script. -->\n'

# The reference's pages: each one's file, title, a line for search and cards, and the headings (as written in the
# source) that start it. A heading not listed stays with the page before it.
REFERENCE = [
    ('index', 'Pedestals', 'What a pedestal shows, its adjust screen, every material, custom pedestals, cabinets and shelves.',
     ['Pedestals']),
    ('ranks', 'Ranks', 'The five ranks, common to legendary: their colors, effects, sounds and light, and adding your own.',
     ['Ranks']),
    ('mob-trophies', 'Mob trophies', 'Mobs and players dropping trophies of themselves, their ranks, and the look they keep.',
     ['Mob trophies']),
    ('collecting', 'Collecting', 'The Trophy Ledger, cabinet sets, leaderboard pedestals, engraving, glass cases and mannequins.',
     ['Collecting', 'Showing them off']),
    ('earned-trophies', 'Earned trophies', 'Trophies for advancements, first kills and milestones, and adding your own from a data pack.',
     ['Earned trophies']),
    ('making-trophies', 'Making trophies', 'Handing out trophies and mob trophies from loot tables, rewards and commands.',
     ['Making trophies']),
    ('for-mods', 'For mods', 'Registering a kind of trophy for your own achievements, and the Java API.',
     ['Trophy kinds (for mods)']),
    ('commands-config', 'Commands and config', 'The command, every server config option, other mods it works with, and the KubeJS binding.',
     ['Commands', 'Config', 'Other mods', 'KubeJS (NeoForge)']),
]

HEADING = re.compile(r'^(#{2,3}) (.+?)\s*$')


def slug(text):
    """The anchor Zensical gives a heading."""
    text = re.sub(r'[^\w\s-]', '', text.lower())
    return re.sub(r'[\s]+', '-', text.strip())


def blocks(text):
    """Each ##/### heading's block as (level, title, body), code blocks skipped."""
    found, current, in_code = [], None, False
    for line in text.splitlines():
        if line.startswith('```'):
            in_code = not in_code
        match = None if in_code else HEADING.match(line)
        if match:
            current = [len(match.group(1)), match.group(2), []]
            found.append(current)
        elif current is not None:
            current[2].append(line)
    return [(level, title, '\n'.join(body).strip('\n')) for level, title, body in found]


def main():
    with open(os.path.join(MOD, 'docs', 'reference.md'), encoding='utf-8') as f:
        found = blocks(f.read())
    starts = {heading: page for page in REFERENCE for heading in page[3]}
    assigned = {page[0]: [] for page in REFERENCE}
    page = REFERENCE[0]
    for level, title, body in found:
        if title in starts:
            page = starts[title]
        assigned[page[0]].append((level, title, body))

    # Where each heading's anchor ends up. (A page's first heading, when it's the page's own title, isn't written.)
    where = {}
    for page in REFERENCE:
        for index, (_, title, _) in enumerate(assigned[page[0]]):
            dropped = index == 0 and title == page[1]
            where[slug(title)] = (page[0], None if dropped else slug(title))

    def relink(text, here):
        def anchor(match):
            found = where.get(match.group(1))
            if found is None:
                return '(#' + match.group(1) + ')'
            name, hash_part = found
            if name == here:
                return '(#' + (hash_part or '') + ')'
            return '(' + name + '.md' + ('#' + hash_part if hash_part else '') + ')'
        text = re.sub(r'\(#([\w-]+)\)', anchor, text)
        # (The site doesn't name the config-editing mods.)
        text = text.replace('; editable in Glazed Menu or Configured', '')
        repo = 'https://github.com/ixDarkLorD/TrophyPedestals/blob/26.1.2/docs/'
        return re.sub(r'\((VERSIONS|ARCHITECTURE)\.md\)', lambda m: '(' + repo + m.group(1) + '.md)', text)

    os.makedirs(os.path.join(DOCS, 'docs', 'reference'), exist_ok=True)
    for name, title, description, _ in REFERENCE:
        out = ['---', 'title: ' + json.dumps(title), 'description: ' + json.dumps(description), '---', '',
               NOTICE.format(source='docs/reference.md'), '# ' + title, '']
        for index, (level, heading, body) in enumerate(assigned[name]):
            if not (index == 0 and heading == title):
                # (On its own page, every section is a ## one: the source's ### ones sat under a ## that's now the page.)
                out += ['## ' + heading, '']
            out += [body, '']
        text = relink('\n'.join(out).rstrip() + '\n', name)
        with open(os.path.join(DOCS, 'docs', 'reference', name + '.md'), 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)

    # The changelog, as the mod keeps it.
    with open(os.path.join(MOD, 'CHANGELOG.md'), encoding='utf-8') as f:
        changelog = f.read()
    changelog = re.sub(r'^# Changelog\n(This file is for listing all the changes to this project\n)?', '', changelog)
    with open(os.path.join(DOCS, 'changelog.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('---\ntitle: "Changelog"\ndescription: "What changed in each version of Trophy Pedestals."\n---\n\n'
                + NOTICE.format(source='CHANGELOG.md') + '# Changelog\n\n' + changelog.strip() + '\n')
    print('Synced the reference ({} pages) and the changelog from {}'.format(len(REFERENCE), MOD))


if __name__ == '__main__':
    main()
